ALTER TABLE public.invoice_resolutions
  ADD COLUMN IF NOT EXISTS resolved_by text NOT NULL DEFAULT '';

CREATE TABLE IF NOT EXISTS public.invoice_resolution_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id text NOT NULL,
  record_id text NOT NULL,
  invoice_no text NOT NULL,
  action text NOT NULL CHECK (action IN ('resolved', 'reopened')),
  reason text NOT NULL DEFAULT '',
  note text NOT NULL DEFAULT '',
  actor_email text NOT NULL,
  occurred_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS invoice_resolution_events_report_occurred_idx
  ON public.invoice_resolution_events (report_id, occurred_at DESC);

ALTER TABLE public.invoice_resolution_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.invoice_resolution_events FROM anon, authenticated;
GRANT SELECT, INSERT ON public.invoice_resolution_events TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.invoice_resolution_events_id_seq TO authenticated;

DROP POLICY IF EXISTS invoice_resolution_events_team_select ON public.invoice_resolution_events;
DROP POLICY IF EXISTS invoice_resolution_events_team_insert ON public.invoice_resolution_events;

CREATE POLICY invoice_resolution_events_team_select ON public.invoice_resolution_events
  FOR SELECT TO authenticated
  USING (EXISTS (SELECT 1 FROM public.invoice_review_members m WHERE m.user_id = (SELECT auth.uid())));

CREATE POLICY invoice_resolution_events_team_insert ON public.invoice_resolution_events
  FOR INSERT TO authenticated
  WITH CHECK (EXISTS (SELECT 1 FROM public.invoice_review_members m WHERE m.user_id = (SELECT auth.uid())));

-- Drivers section: one row per driver, vehicle and delivery day, built from the uploaded reports.

CREATE TABLE IF NOT EXISTS public.driver_days (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  delivery_date date NOT NULL,
  driver_key text NOT NULL,
  driver_name text NOT NULL,
  vehicle text NOT NULL,
  invoice_count integer NOT NULL DEFAULT 0,
  trip_count integer NOT NULL DEFAULT 0,
  trips text NOT NULL DEFAULT '',
  weight numeric NOT NULL DEFAULT 0,
  first_seen_by text NOT NULL DEFAULT '',
  updated_by text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  reviewed_by text,
  reviewed_at timestamptz,
  review_note text NOT NULL DEFAULT '',
  CONSTRAINT driver_days_unique UNIQUE (delivery_date, driver_key, vehicle),
  CONSTRAINT driver_days_vehicle_not_blank CHECK (length(btrim(vehicle)) > 0)
);

CREATE INDEX IF NOT EXISTS driver_days_date_idx ON public.driver_days (delivery_date DESC);
CREATE INDEX IF NOT EXISTS driver_days_driver_idx ON public.driver_days (driver_key, delivery_date DESC);
CREATE INDEX IF NOT EXISTS driver_days_vehicle_idx ON public.driver_days (vehicle, delivery_date DESC);

-- The server writes who did it, so a reviewer cannot put someone else's email on a record.
CREATE OR REPLACE FUNCTION public.driver_days_stamp()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  actor text := coalesce((SELECT auth.jwt() ->> 'email'), '');
BEGIN
  NEW.updated_at := now();
  NEW.updated_by := actor;
  IF TG_OP = 'INSERT' THEN
    NEW.first_seen_by := actor;
    IF NEW.reviewed_at IS NOT NULL THEN NEW.reviewed_by := actor; END IF;
  ELSE
    NEW.first_seen_by := OLD.first_seen_by;
    IF NEW.reviewed_at IS DISTINCT FROM OLD.reviewed_at THEN
      NEW.reviewed_by := CASE WHEN NEW.reviewed_at IS NULL THEN NULL ELSE actor END;
    ELSE
      NEW.reviewed_by := OLD.reviewed_by;
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS driver_days_stamp_trg ON public.driver_days;
CREATE TRIGGER driver_days_stamp_trg
  BEFORE INSERT OR UPDATE ON public.driver_days
  FOR EACH ROW EXECUTE FUNCTION public.driver_days_stamp();

ALTER TABLE public.driver_days ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.driver_days FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.driver_days TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.driver_days_id_seq TO authenticated;

DROP POLICY IF EXISTS driver_days_team_select ON public.driver_days;
DROP POLICY IF EXISTS driver_days_team_insert ON public.driver_days;
DROP POLICY IF EXISTS driver_days_team_update ON public.driver_days;
DROP POLICY IF EXISTS driver_days_admin_delete ON public.driver_days;

CREATE POLICY driver_days_team_select ON public.driver_days
  FOR SELECT TO authenticated
  USING (EXISTS (SELECT 1 FROM public.invoice_review_members m WHERE m.user_id = (SELECT auth.uid())));

CREATE POLICY driver_days_team_insert ON public.driver_days
  FOR INSERT TO authenticated
  WITH CHECK (EXISTS (SELECT 1 FROM public.invoice_review_members m WHERE m.user_id = (SELECT auth.uid())));

CREATE POLICY driver_days_team_update ON public.driver_days
  FOR UPDATE TO authenticated
  USING (EXISTS (SELECT 1 FROM public.invoice_review_members m WHERE m.user_id = (SELECT auth.uid())))
  WITH CHECK (EXISTS (SELECT 1 FROM public.invoice_review_members m WHERE m.user_id = (SELECT auth.uid())));

-- Only the admin can remove history.
CREATE POLICY driver_days_admin_delete ON public.driver_days
  FOR DELETE TO authenticated
  USING (EXISTS (SELECT 1 FROM public.invoice_review_members m WHERE m.user_id = (SELECT auth.uid()) AND m.role = 'admin'));

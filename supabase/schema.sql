CREATE TABLE IF NOT EXISTS public.invoice_review_members (
  user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  added_at timestamptz NOT NULL DEFAULT now(),
  role text NOT NULL DEFAULT 'reviewer' CHECK (role IN ('admin', 'reviewer')),
  must_change_password boolean NOT NULL DEFAULT false
);

ALTER TABLE public.invoice_review_members ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.invoice_review_members FROM anon, authenticated;
GRANT SELECT ON public.invoice_review_members TO authenticated;
GRANT UPDATE (must_change_password) ON public.invoice_review_members TO authenticated;
DROP POLICY IF EXISTS invoice_review_members_read_own ON public.invoice_review_members;
CREATE POLICY invoice_review_members_read_own ON public.invoice_review_members
  FOR SELECT TO authenticated
  USING (user_id = (SELECT auth.uid()));
DROP POLICY IF EXISTS invoice_review_members_update_own_password_flag ON public.invoice_review_members;
CREATE POLICY invoice_review_members_update_own_password_flag ON public.invoice_review_members
  FOR UPDATE TO authenticated
  USING (user_id = (SELECT auth.uid()))
  WITH CHECK (user_id = (SELECT auth.uid()));

CREATE TABLE IF NOT EXISTS public.invoice_resolutions (
  report_id text NOT NULL,
  record_id text NOT NULL,
  invoice_no text NOT NULL,
  status text NOT NULL CHECK (status IN ('resolved', 'unresolved')),
  reason text NOT NULL DEFAULT '',
  note text NOT NULL DEFAULT '',
  resolved_by text NOT NULL DEFAULT '',
  resolved_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (report_id, record_id)
);

ALTER TABLE public.invoice_resolutions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.invoice_resolutions FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.invoice_resolutions TO authenticated;

DROP POLICY IF EXISTS invoice_resolutions_team_select ON public.invoice_resolutions;
DROP POLICY IF EXISTS invoice_resolutions_team_insert ON public.invoice_resolutions;
DROP POLICY IF EXISTS invoice_resolutions_team_update ON public.invoice_resolutions;
DROP POLICY IF EXISTS invoice_resolutions_team_delete ON public.invoice_resolutions;

CREATE POLICY invoice_resolutions_team_select ON public.invoice_resolutions
  FOR SELECT TO authenticated
  USING (EXISTS (SELECT 1 FROM public.invoice_review_members m WHERE m.user_id = (SELECT auth.uid())));
CREATE POLICY invoice_resolutions_team_insert ON public.invoice_resolutions
  FOR INSERT TO authenticated
  WITH CHECK (EXISTS (SELECT 1 FROM public.invoice_review_members m WHERE m.user_id = (SELECT auth.uid())));
CREATE POLICY invoice_resolutions_team_update ON public.invoice_resolutions
  FOR UPDATE TO authenticated
  USING (EXISTS (SELECT 1 FROM public.invoice_review_members m WHERE m.user_id = (SELECT auth.uid())))
  WITH CHECK (EXISTS (SELECT 1 FROM public.invoice_review_members m WHERE m.user_id = (SELECT auth.uid())));
CREATE POLICY invoice_resolutions_team_delete ON public.invoice_resolutions
  FOR DELETE TO authenticated
  USING (EXISTS (SELECT 1 FROM public.invoice_review_members m WHERE m.user_id = (SELECT auth.uid())));

CREATE TABLE IF NOT EXISTS public.invoice_resolution_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id text NOT NULL,
  record_id text NOT NULL,
  invoice_no text NOT NULL,
  action text NOT NULL CHECK (action IN ('resolved', 'reopened')),
  reason text NOT NULL DEFAULT '',
  note text NOT NULL DEFAULT '',
  actor_email text NOT NULL,
  occurred_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS invoice_resolution_events_report_occurred_idx
  ON public.invoice_resolution_events (report_id, occurred_at DESC);

ALTER TABLE public.invoice_resolution_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.invoice_resolution_events FROM anon, authenticated;
GRANT SELECT, INSERT ON public.invoice_resolution_events TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.invoice_resolution_events_id_seq TO authenticated;
CREATE POLICY invoice_resolution_events_team_select ON public.invoice_resolution_events
  FOR SELECT TO authenticated
  USING (EXISTS (SELECT 1 FROM public.invoice_review_members m WHERE m.user_id = (SELECT auth.uid())));
CREATE POLICY invoice_resolution_events_team_insert ON public.invoice_resolution_events
  FOR INSERT TO authenticated
  WITH CHECK (EXISTS (SELECT 1 FROM public.invoice_review_members m WHERE m.user_id = (SELECT auth.uid())));

ALTER PUBLICATION supabase_realtime
  ADD TABLE public.invoice_resolution_events;
